@app.route("/record", methods=["POST"])
def record():

    if not validate_csrf():
        return "Невалидна заявка. Моля, опитайте отново.", 400

    username = session.get("poll_username")
    demo_code = session.get("poll_demo_code")
    poll_choice = request.form.get("poll_choice", "").strip()

    if not username or not demo_code:
        return redirect(url_for("index"))

    if poll_choice not in POLL_OPTIONS:
        return "Невалиден избор.", 400

    timestamp = datetime.now().astimezone().strftime("%Y-%m-%d %H:%M:%S %Z")

    action = "POLL_SELECTION: " + poll_choice

    with get_db() as connection:

        cursor = connection.execute(
            """
            INSERT INTO events (
                username,
                test_code,
                action,
                timestamp
            )
            VALUES (?, ?, ?, ?)
            """,
            (
                username,
                demo_code,
                action,
                timestamp
            )
        )

        event_id = cursor.lastrowid

    email_sent = send_email_report(
        event_id,
        username,
        demo_code,
        poll_choice,
        timestamp
    )

    print("EVENT SAVED:", event_id)
    print("EMAIL SENT:", email_sent)

    session.pop("poll_username", None)
    session.pop("poll_demo_code", None)
    session.pop("csrf_token", None)

    return SUCCESS_PAGE


