@app.route("/start", methods=["POST"])
def start():

    if not validate_csrf():
        return "Невалидна заявка. Моля, опитайте отново.", 400

    username = request.form.get("username", "").strip()
    demo_code = request.form.get("test_code", "").strip()

    if not username or not demo_code:
        return "Моля, попълнете всички полета.", 400

    if len(username) > 100 or len(demo_code) > 100:
        return "Въведените данни са прекалено дълги.", 400

    session["poll_username"] = username
    session["poll_demo_code"] = demo_code

    session.pop("csrf_token", None)

    return redirect(url_for("survey"))


