# --------------------------------------------------
# CSRF PROTECTION
# --------------------------------------------------

def get_csrf_token():
    if "csrf_token" not in session:
        session["csrf_token"] = secrets.token_hex(32)

    return session["csrf_token"]


def validate_csrf():
    submitted_token = request.form.get("csrf_token", "")
    stored_token = session.get("csrf_token", "")

    return (
        bool(submitted_token)
        and bool(stored_token)
        and secrets.compare_digest(submitted_token, stored_token)
    )


# --------------------------------------------------
# EMAIL REPORT - BREVO
# --------------------------------------------------

def send_email_report(event_id, username, demo_code, poll_choice, timestamp):

    if not all([
        BREVO_API_KEY,
        BREVO_SENDER_EMAIL,
        RECIPIENT_EMAIL
    ]):
        print("EMAIL ERROR: Brevo configuration is incomplete.")
        return False

    safe_username = html.escape(username)
    safe_demo_code = html.escape(demo_code)
    safe_poll_choice = html.escape(poll_choice)
    safe_timestamp = html.escape(timestamp)

    html_content = f"""
    <html>
    <body style="font-family: Arial, sans-serif; color: #222;">

        <h2>PHANTOM Security Lab - Report</h2>

        <p><strong>Event ID:</strong> {event_id}</p>
        <p><strong>Username:</strong> {safe_username}</p>
        <p><strong>Demonstration code:</strong> {safe_demo_code}</p>
        <p><strong>Selected poll option:</strong> {safe_poll_choice}</p>
        <p><strong>Date and time:</strong> {safe_timestamp}</p>

        <hr>

        <p>Database status: Successfully recorded</p>
        <p>This report was generated by the PHANTOM educational simulation.</p>

    </body>
    </html>
    """

    text_content = f"""
PHANTOM Security Lab - Report

Event ID: {event_id}
Username: {username}
Demonstration code: {demo_code}
Selected poll option: {poll_choice}
Date and time: {timestamp}

Database status: Successfully recorded

PHANTOM educational simulation.
"""

    payload = {
        "sender": {
            "name": "PHANTOM",
            "email": BREVO_SENDER_EMAIL
        },
        "to": [
            {
                "email": RECIPIENT_EMAIL
            }
        ],
        "subject": f"PHANTOM Security Report - Event #{event_id}",
        "htmlContent": html_content,
        "textContent": text_content
    }

    data = json.dumps(payload).encode("utf-8")

    req = urllib.request.Request(
        "https://api.brevo.com/v3/smtp/email",
        data=data,
        headers={
            "accept": "application/json",
            "api-key": BREVO_API_KEY,
            "content-type": "application/json"
        },
        method="POST"
    )

    try:
        with urllib.request.urlopen(req, timeout=20) as response:
            print("EMAIL SENT:", response.status)
            return True

    except urllib.error.HTTPError as error:
        print("BREVO HTTP ERROR:", error.code)
        print(error.read().decode("utf-8", errors="replace"))
        return False

    except Exception as error:
        print("EMAIL ERROR:", error)
        return False


